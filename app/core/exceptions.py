def send_exception_alert(title: str, status_code: str, message: str, details: Any = None, module_name: str = "Exception Handler"):
    try:
        if not settings.FEATURE_TEAMS or not settings.TEAMS_WEBHOOK_URL:
            return

        service = TeamsWebhookService(settings.TEAMS_WEBHOOK_URL)
        today = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

        facts = {
            "Date": today,
            "Module": module_name,
            "Status Code": str(status_code),
            "Message": message,
        }
        
        # Extract specific fields from details if available (for UserJourneyGlitchException)
        # We create a copy to avoid modifying the original details object and to filter out promoted keys
        display_details = details
        if isinstance(details, dict):
            display_details = details.copy()
            
            if "request_id" in display_details:
                facts["Request ID"] = str(display_details.pop("request_id"))
            if "user_id" in display_details:
                facts["User ID"] = str(display_details.pop("user_id"))
            if "file_name" in display_details:
                facts["File Name"] = str(display_details.pop("file_name"))
            if "line_no" in display_details:
                facts["Line No"] = str(display_details.pop("line_no"))
            # Module is already passed as an argument and added to facts, so we can remove it from details if present
            if "module" in display_details:
                display_details.pop("module")
        
        if display_details:
            facts["Details"] = str(display_details)

        service.send(
            title=title,
            facts=facts,
            footer="Auto-generated by Exception Handler"
        )
    except Exception as e:
        logger.error(f"Failed to send Teams alert: {str(e)}")


