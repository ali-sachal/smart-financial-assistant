class AppException(Exception):
    """Custom exception class for application-related errors"""

    def __init__(
        self,
        status_code: int,
        message: str,
        details: Optional[Dict[str, Any]] = None,
        alert_title: str = "AppException Alert",
        module_name: str = "Exception Handler",
        send_alert: Optional[bool] = None
    ):
        self.status_code = status_code
        self.message = message
        self.details = details or {}
        super().__init__(self.message)
        
        # Default: Only send alerts for 5xx server errors, unless explicitly requested
        should_send = send_alert
        if should_send is None:
            should_send = status_code >= 500
            
        if should_send:
            send_exception_alert(
                title=alert_title,
                status_code=str(self.status_code),
                message=self.message,
                details=self.details,
                module_name=module_name
            )

    def to_dict(self) -> Dict[str, Any]:
        """Convert exception to dictionary format"""
        return {
            "status_code": self.status_code,
            "message": self.message,
            "details": self.details
        }


class UserJourneyGlitchException(AppException):
    """Exception for user journey glitches"""

    def __init__(
        self,
        user_id: str,
        module_name: str,
        message: str = "User journey glitch detected",
        original_error: Optional[Exception] = None,
        file_name: Optional[str] = None,
        line_no: Optional[int] = None,
        status_code: int = status.HTTP_500_INTERNAL_SERVER_ERROR
    ):
       
        resolved_file_name = file_name or "unknown"
        resolved_line_no = str(line_no) if line_no else "unknown"

        if not file_name or not line_no:
            if original_error:
                tb = original_error.__traceback__
                if tb:
                    while tb.tb_next:
                        tb = tb.tb_next
                    resolved_file_name = tb.tb_frame.f_code.co_filename
                    resolved_line_no = str(tb.tb_lineno)
            else:
                try:
                    # 1 is caller (instantiation)
                    frame = sys._getframe(1)
                    resolved_file_name = frame.f_code.co_filename
                    resolved_line_no = str(frame.f_lineno)
                except ValueError:
                    pass

        details = {
            "user_id": user_id,
            "request_id": REQUEST_ID_CTX_VAR.get(),
            "module": module_name,
            "file_name": resolved_file_name,
            "line_no": resolved_line_no,
        }
        
        if original_error:
             details["original_error"] = str(original_error)

        super().__init__(
            status_code=status_code,
            message=message,
            details=details,
            alert_title="User Journey Glitch Alert",
            module_name=module_name,
            send_alert=True  # Always alert for glitches
        )


def _get_request_id(request: Request) -> str:
    rid = getattr(request.state, "request_id", None)
    if rid:
        return rid
    return request.headers.get("x-request-id") or request.headers.get("X-Request-ID") or str(uuid.uuid4())


def _headers_with_context(request: Request) -> Dict[str, str]:
    rid = _get_request_id(request)
    start_time = getattr(request.state, "start_time", None)
    duration_ms = None
    if start_time is not None:
        duration_ms = int((time.perf_counter() - start_time) * 1000)
    headers = {"X-Request-ID": rid}
    if duration_ms is not None:
        headers["X-Response-Time"] = f"{duration_ms}ms"
    return headers


async def app_exception_handler(request: Request, exc: AppException) -> JSONResponse:
    logger.error(f"AppException: {exc.status_code} - {exc.message} - details={exc.details}", exc_info=True)

    response = ErrorResponse(
        success=False,
        message=exc.message,
        errors=exc.details if exc.details else None,
        result=None
    )

    return JSONResponse(
        status_code=exc.status_code,
        content=jsonable_encoder(response),
        headers=_headers_with_context(request),
    )


async def validation_exception_handler(request: Request, exc: RequestValidationError) -> JSONResponse:
    logger.error(f"Validation error: {exc.errors()}", exc_info=True)

    error_details: List[Dict[str, Any]] = []
    for error in exc.errors():
        error_details.append({
            "field": ".".join(str(loc) for loc in error.get("loc", [])),
            "message": error.get("msg", ""),
            "type": error.get("type", "")
        })

    response = ErrorResponse(
        success=False,
        message=Message.INVALID_INPUT,
        errors=error_details,
        result=None
    )

    return JSONResponse(
        status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
        content=jsonable_encoder(response),
        headers=_headers_with_context(request),
    )


async def pydantic_validation_exception_handler(request: Request, exc: ValidationError) -> JSONResponse:
    logger.error(f"Pydantic validation error: {exc.errors()}", exc_info=True)

    error_details: List[Dict[str, Any]] = []
    for error in exc.errors():
        error_details.append({
            "field": ".".join(str(loc) for loc in error.get("loc", [])),
            "message": error.get("msg", ""),
            "type": error.get("type", "")
        })

    response = ErrorResponse(
        success=False,
        message=Message.INVALID_INPUT,
        errors=error_details,
        result=None
    )

    return JSONResponse(
        status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
        content=jsonable_encoder(response),
        headers=_headers_with_context(request),
    )


def _is_preselected_code(code: int) -> bool:
    return code in [
        ResponseCode.SUCCESS, ResponseCode.CREATED, ResponseCode.BAD_REQUEST,
        ResponseCode.UNAUTHORIZED, ResponseCode.FORBIDDEN, ResponseCode.NOT_FOUND,
        ResponseCode.METHOD_NOT_ALLOWED, ResponseCode.CONFLICT, ResponseCode.PAYLOAD_TOO_LARGE,
        ResponseCode.UNSUPPORTED_MEDIA_TYPE, ResponseCode.UNPROCESSABLE_ENTITY,
        ResponseCode.TOO_MANY_REQUESTS, ResponseCode.INTERNAL_SERVER_ERROR,
        ResponseCode.SERVICE_UNAVAILABLE
    ]


async def http_exception_handler(request: Request, exc: HTTPException) -> JSONResponse:
    logger.error(f"HTTP exception: {exc.status_code} - {exc.detail}", exc_info=True)

    errors = None
    if not _is_preselected_code(exc.status_code):
        errors = str(exc.detail)

    response = ErrorResponse(
        success=False,
        message=str(exc.detail),
        errors=errors,
        result=None
    )

    return JSONResponse(
        status_code=exc.status_code,
        content=jsonable_encoder(response),
        headers=_headers_with_context(request),
    )


async def sqlalchemy_exception_handler(request: Request, exc: SQLAlchemyError) -> JSONResponse:
    logger.error(f"Database error: {str(exc)}", exc_info=True)

    # 503 is in ResponseCode, so errors should be None according to requirements
    response = ErrorResponse(
        success=False,
        message=Message.DATABASE_CONNECTION_ERROR,
        errors=None, 
        result=None
    )

    return JSONResponse(
        status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
        content=jsonable_encoder(response),
        headers=_headers_with_context(request),
    )


async def generic_exception_handler(request: Request, exc: Exception) -> JSONResponse:
    logger.error(f"Unexpected error: {str(exc)}", exc_info=True)

    send_exception_alert(
        title="Internal Server Error Alert",
        status_code=str(status.HTTP_500_INTERNAL_SERVER_ERROR),
        message=str(exc),
        details="See application logs for full traceback"
    )

    # 500 is in ResponseCode, so errors should be None according to requirements
    response = ErrorResponse(
        success=False,
        message=Message.INTERNAL_SERVER_ERROR,
        errors=None,
        result=None
    )

    return JSONResponse(
        status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
        content=jsonable_encoder(response),
        headers=_headers_with_context(request),
    )


def register_exception_handlers(app):
    app.add_exception_handler(AppException, app_exception_handler)
    app.add_exception_handler(RequestValidationError, validation_exception_handler)
    app.add_exception_handler(ValidationError, pydantic_validation_exception_handler)
    app.add_exception_handler(HTTPException, http_exception_handler)
    app.add_exception_handler(SQLAlchemyError, sqlalchemy_exception_handler)
    app.add_exception_handler(Exception, generic_exception_handler)
